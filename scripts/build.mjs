// Generates every file derived from the rules and the skill, so they cannot drift:
//   docs/RULES.md            the rule catalog, from src/core/rules
//   schema.json              JSON schema for .deslopr.json
//   adapters/*               ready-to-copy rule files for each agent
//   dist/deslopr.md       the whole skill in one file, to paste into any chat
//   dist/deslopr-compact.md  under 1,500 characters, for custom-instruction fields
// `node scripts/build.mjs --check` fails when a committed file is out of date (CI runs it).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RULES, DOMAINS } from '../src/core/rules/index.js';
import { VERSION } from '../src/core/index.js';
import { pointerBlock, cursorRule, windsurfRule, plainRule, compactFile, COMPACT_RULES } from '../src/node/templates.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const outputs = new Map();
const emit = (rel, content) => outputs.set(rel, content.replace(/\r\n/g, '\n'));

// docs/RULES.md
{
  const DOMAIN_TITLE = { prose: 'Writing', code: 'Code', ui: 'Interfaces', repo: 'Repository hygiene' };
  const lines = [
    '<!-- Generated by scripts/build.mjs from src/core/rules. Do not edit by hand. -->',
    '<!-- deslopr-disable-file -- the catalog shows slop examples -->',
    '# Rules',
    '',
    `${RULES.length} rules. Severity: \`error\` is almost always a real defect, \`warn\` is usually real (read the line), \`info\` counts toward the slop index and shows in clusters or with \`--verbose\`.`,
    '',
    'Change a severity or turn a rule off in `.deslopr.json`; suppress one line with `deslopr-disable-next-line <rule> -- <reason>`.',
    '',
    `${RULES.filter((r) => r.autofix).length} rules have a safe autofix, marked **autofix** below: \`deslopr fix\` previews it as a diff and \`deslopr fix --write\` applies it. The fix covers only the unambiguous cases; everything else stays a finding for a person.`,
    '',
  ];
  for (const d of DOMAINS) {
    const list = RULES.filter((r) => r.domain === d);
    lines.push(`## ${DOMAIN_TITLE[d]}`, '', '| Rule | Severity | What it catches |', '|---|---|---|');
    for (const r of list) lines.push(`| [\`${r.id}\`](#${r.id.replace(/[/]/g, '').toLowerCase()}) | ${r.severity}${r.autofix ? ', autofix' : ''} | ${r.name.replace(/\|/g, '\\|')} |`);
    lines.push('');
    for (const r of list) {
      lines.push(`### ${r.id}`, '', `**${r.name}** · ${r.severity}${r.autofix ? ' · autofix' : ''}${r.patterns?.some((p) => p.lang === 'fr') ? ' · English and French' : ''}`, '', `**Why.** ${r.why}`, '', `**Fix.** ${r.fix}`, '');
      if (r.options) lines.push(`**Options.** \`${JSON.stringify(r.options)}\``, '');
      const block = (ex) => {
        const c = typeof ex === 'string' ? { path: 'example.md', text: ex } : ex;
        const lang = c.path.split('.').pop();
        return ['```' + (lang === 'md' ? 'markdown' : lang), c.text.trimEnd(), '```'].join('\n');
      };
      lines.push('Flags:', '', ...r.examples.bad.map(block), '', 'Does not flag:', '', ...r.examples.good.map(block), '');
      if (r.autofix) {
        const changed = r.examples.fixes.filter((f) => f.output !== f.text);
        const kept = r.examples.fixes.filter((f) => f.output === f.text);
        lines.push('`deslopr fix` changes:', '');
        for (const f of changed) lines.push(block({ path: 'example.md', ...f }), '', 'into', '', block({ path: 'example.md', ...f, text: f.output }), '');
        lines.push('and leaves alone:', '', ...kept.map((f) => block({ path: 'example.md', ...f })), '');
      }
    }
  }
  emit('docs/RULES.md', lines.join('\n'));
}

// schema.json
{
  const ids = RULES.map((r) => r.id);
  const sev = { type: 'string', enum: ['error', 'warn', 'info', 'off'] };
  const schema = {
    $schema: 'http://json-schema.org/draft-07/schema#',
    title: 'deslopr configuration',
    type: 'object',
    properties: {
      $schema: { type: 'string' },
      ignore: { type: 'array', items: { type: 'string' }, description: 'Glob patterns of files to skip.' },
      rules: {
        type: 'object',
        description: 'Rule id, domain/* or domain, mapped to a severity or to { severity, ...options }.',
        propertyNames: { anyOf: [{ enum: ids }, { pattern: `^(${DOMAINS.join('|')})(/\\*)?$` }, { const: '*' }] },
        additionalProperties: { anyOf: [sev, { type: 'object', properties: { severity: sev } }] },
      },
      allow: { type: 'array', items: { type: 'string' }, description: 'Words and phrases never reported (brand names, terms of art).' },
      languages: { type: 'array', items: { enum: ['en', 'fr'] } },
      domains: { type: 'array', items: { enum: DOMAINS } },
      failOn: { enum: ['error', 'warn', 'info', 'none'] },
      hook: {
        type: 'object',
        properties: { enabled: { type: 'boolean' }, severity: { enum: ['error', 'warn', 'info'] }, onStop: { type: 'boolean' } },
      },
    },
    additionalProperties: false,
  };
  emit('schema.json', JSON.stringify(schema, null, 2) + '\n');
}

// adapters/
{
  const opts = { skillPath: '.claude/skills/deslopr', cmd: 'npx deslopr' };
  emit('adapters/AGENTS.md', pointerBlock({ ...opts, skillPath: '.agents/skills/deslopr' }));
  emit('adapters/CLAUDE.md', pointerBlock(opts));
  emit('adapters/GEMINI.md', pointerBlock({ ...opts, skillPath: '.agents/skills/deslopr' }));
  emit('adapters/copilot-instructions.md', pointerBlock({ ...opts, skillPath: '.agents/skills/deslopr' }));
  emit('adapters/cursor/deslopr.mdc', cursorRule({ ...opts, skillPath: '.agents/skills/deslopr' }));
  emit('adapters/windsurf/deslopr.md', windsurfRule({ ...opts, skillPath: '.agents/skills/deslopr' }));
  emit('adapters/cline/deslopr.md', plainRule({ ...opts, skillPath: '.agents/skills/deslopr' }));
}

// dist/
{
  const skillDir = path.join(ROOT, 'skills', 'deslopr');
  const strip = (s) => s.replace(/^---[\s\S]*?\n---\n/, '').replace(/<!-- deslopr-disable-file[^>]*-->\n?/g, '').trim();
  const skill = strip(fs.readFileSync(path.join(skillDir, 'SKILL.md'), 'utf8'))
    .replace(/\[references\/(\w+)\.md\]\(references\/\w+\.md\)/g, (_, n) => `the "${n}" part below`)
    .replace(/`references\/(\w+)\.md`/g, (_, n) => `the "${n}" part below`);
  const parts = ['writing', 'code', 'ui', 'gate'].map((n) => strip(fs.readFileSync(path.join(skillDir, 'references', `${n}.md`), 'utf8')).replace(/^# /, `# Part: ${n} · `));
  const header = `<!-- deslopr-disable-file -- complete skill in one file; quotes slop on purpose -->\n<!-- deslopr ${VERSION}. Generated by scripts/build.mjs from skills/deslopr. Paste into any chat, or save as a project instruction file. -->\n`;
  emit('dist/deslopr.md', `${header}\n${skill}\n\n${parts.join('\n\n')}\n`);
  emit('dist/deslopr-compact.md', compactFile());
  if (COMPACT_RULES.length > 1500) throw new Error(`compact rules are ${COMPACT_RULES.length} characters; the limit is 1500`);
}

let stale = 0;
for (const [rel, content] of outputs) {
  const file = path.join(ROOT, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current === content) continue;
  if (check) {
    process.stderr.write(`out of date: ${rel}\n`);
    stale++;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    process.stdout.write(`wrote ${rel}\n`);
  }
}
if (check && stale) {
  process.stderr.write(`${stale} generated file(s) out of date; run \`npm run build\`.\n`);
  process.exit(1);
}
if (check) process.stdout.write(`generated files up to date (${outputs.size})\n`);
